  const { enqueueSubmission } = await import('../lib/submission-queue');
  const { setReviewPermissions } = await import('../lib/permissions');
  const editor={id:'editor',company:'review-test',role:'editor' as const};
  const approver={...editor,id:'approver',canReview:true,canApprove:true};
  const sender={...editor,id:'sender',role:'sender' as const};
  const raw={supplierId:'101',buyer:'fixture',date:'2026-10-11',reference:'',notes:'',warehouse:'',po:'',vatMode:'exclusive',discount:'0',items:[{productId:'201',quantity:'1',price:'8.50'}]};
