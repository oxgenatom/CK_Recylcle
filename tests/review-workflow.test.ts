    await assert.rejects(setReviewPermissions(editor,{identity:'approver',canReview:true,canApprove:true,reason:'unauthorized'}),/เฉพาะผู้ดูแล/);
    const admin={...editor,id:'admin',role:'admin' as const};
    await assert.rejects(setReviewPermissions(admin,{identity:'approver',canReview:true,canApprove:true,reason:''}));
    await assert.rejects(setReviewPermissions({...admin,company:'other'},{identity:'approver',canReview:true,canApprove:true,reason:'wrong company'}),/เฉพาะผู้ดูแล/);
    await setReviewPermissions(admin,{identity:'approver',canReview:true,canApprove:true,reason:'explicit QA grant'});
    assert.equal((await db().query('SELECT reason FROM membership_permission_events')).rows[0].reason,'explicit QA grant');
    let d=await r.save(approver,raw);
    const originalHash=submissionHash(d);
    d=await reviewAction(approver,d.id,d.version,'request-review','');
    assert.equal(d.status,'pending_review');
    await assert.rejects(reviewAction({...editor,role:'admin'},d.id,d.version,'approve',''),/ไม่มีสิทธิ์/);
    await assert.rejects(reviewAction(editor,d.id,d.version,'cancel-review',''),/เฉพาะผู้ขอ/);
    const results=await Promise.allSettled([reviewAction(approver,d.id,d.version,'approve','self approval authorized'),reviewAction(approver,d.id,d.version,'approve','duplicate')]);
    assert.equal(results.filter(x=>x.status==='fulfilled').length,1);
    d=await r.read(approver,d.id);assert.equal(d.status,'approved');assert.equal(submissionHash(d),originalHash);
    await assert.rejects(r.save(approver,{...raw,buyer:'stale'},d.id,d.version-1),/เปลี่ยนแล้ว/);
    d=await r.save(approver,{...raw,buyer:'changed'},d.id,d.version);
    assert.equal(d.status,'draft');assert.notEqual(submissionHash(d),originalHash);
    assert.equal((await db().query('SELECT status FROM draft_reviews WHERE document_id=$1',[d.id])).rows[0].status,'invalidated');
    d=await reviewAction(approver,d.id,d.version,'request-review','');
    await assert.rejects(reviewAction(approver,d.id,d.version,'return',''),/เหตุผล/);
    d=await reviewAction(approver,d.id,d.version,'return','fix buyer');assert.equal(d.status,'draft');
    d=await reviewAction(approver,d.id,d.version,'request-review','');
    d=await reviewAction(approver,d.id,d.version,'cancel-review','cancel');assert.equal(d.status,'draft');
    d=await reviewAction(approver,d.id,d.version,'request-review','');
    await db().query("UPDATE memberships SET can_approve=false WHERE identity='approver'");
    await assert.rejects(reviewAction(approver,d.id,d.version,'approve',''),/เพิกถอน/);
    await db().query("UPDATE memberships SET can_approve=true WHERE identity='approver'");
    d=await reviewAction(approver,d.id,d.version,'approve','');
    await assert.rejects(r.read({...approver,company:'other'},d.id),/ไม่พบ/);
    await assert.rejects(r.save(sender,raw),/ไม่มีสิทธิ์/);
    // Simulated Production snapshot; all subsequent HTTP uses an intercepted fake fetch.
    await db().query("UPDATE receiving_documents SET mode='live',body=jsonb_set(body,'{catalogEnvironment}','\"production\"') WHERE id=$1",[d.id]);
    Object.assign(process.env,{FLOW_MODE:'live',FLOW_ENVIRONMENT:'production'});
    d=await r.read(approver,d.id);
    await db().query("UPDATE draft_reviews SET environment='production',request_hash=$2 WHERE document_id=$1 AND status='approved'",[d.id,submissionHash(d)]);
    await assert.rejects(enqueueSubmission(sender,d.id,d.version,'sandbox'),/ไม่พบ/);
    const queued=await Promise.allSettled([enqueueSubmission(sender,d.id,d.version,'production'),enqueueSubmission(sender,d.id,d.version,'production')]);
    assert.equal(queued.filter(x=>x.status==='fulfilled').length,1);
    await assert.rejects(enqueueSubmission(sender,d.id,d.version,'production'),/ห้ามกดซ้ำ/);
    assert.equal((await db().query('SELECT count(*)::int AS n FROM submission_attempts')).rows[0].n,0);
    await db().query("UPDATE memberships SET active=false WHERE identity='sender'");
    await assert.rejects(enqueueSubmission(sender,d.id,d.version,'production'),/ไม่มีสิทธิ์/);
    await db().query("UPDATE memberships SET active=true WHERE identity='sender'");
    Object.assign(process.env,{APP_COMPANY_ID:'review-test',FLOW_BASE_URL:'https://openapi.flowaccount.com/v1',FLOW_PRODUCTION_READ_APPROVED:'true',FLOW_PRODUCTION_SUBMISSION_ENABLED:'true',FLOW_PRODUCTION_CLIENT_ID:'fixture-only',FLOW_PRODUCTION_CLIENT_SECRET:'fixture-only',CK_SUBMISSION_WORKER:'true'});
    await db().query("UPDATE receiving_documents SET body=jsonb_set(body,'{items,0,product,price}','\"8.5000\"') WHERE id=$1",[d.id]);
    d=await r.read(approver,d.id);
    let posts=0,catalogChanged=false;
    globalThis.fetch=async(input,options)=>{
      const url=String(input);assert.ok(url.startsWith('https://openapi.flowaccount.com/v1/'));
      if(url.endsWith('/token'))return Response.json({access_token:'fixture-token',token_type:'bearer',expires_in:3600});
      if(url.endsWith('/purchases')){assert.equal(options?.method,'POST');posts++;throw Error('simulated_timeout');}
      if(url.endsWith('/purchases/123')){const expected=payload(d.body,d.id);return Response.json({status:true,data:{...expected,totalWithoutVat:expected.grandTotal-expected.vatAmount,documentId:123,documentSerial:'RI-fixture-only',status:1,statusString:'awaiting'}});}
      const s=d.body.supplier,p=d.body.items[0].product;
      if(url.includes('/contacts?'))return Response.json({status:true,data:{currentPage:1,total:1,list:[{id:s.id,contactType:5,contactName:s.name,contactAddress:s.address,contactTaxId:s.taxId,contactBranch:s.branch,contactBranchCode:s.branchCode,contactGroup:s.group,contactZipCode:s.zip}]}});
      if(url.includes('/product-masters?'))return Response.json({status:true,data:{currentPage:1,total:1,list:[{id:p.masterId,name:catalogChanged?'Changed catalog name':p.name,type:p.type,buySettings:{vatType:p.vatType},productLists:[{id:p.id,unitId:p.unitId,code:p.code,unitName:p.unit,buyPrice:p.price}]}]}});
      throw Error('unexpected_http_route');
    };
    await db().query("UPDATE submission_jobs SET status='running',auth_expires_at=now()-interval '1 minute' WHERE document_id=$1",[d.id]);
    await assert.rejects(r.submit(sender,d.id,d.version,'production',true),/session/);assert.equal(posts,0);
    await db().query("UPDATE submission_jobs SET auth_expires_at=now()+interval '1 hour' WHERE document_id=$1",[d.id]);
    await db().query("UPDATE memberships SET can_approve=false WHERE identity='approver'");
    await assert.rejects(r.submit(sender,d.id,d.version,'production',true),/approval/);assert.equal(posts,0);
    await db().query("UPDATE memberships SET can_approve=true WHERE identity='approver'");
    await db().query("UPDATE memberships SET active=false WHERE identity='sender'");
    await assert.rejects(r.submit(sender,d.id,d.version,'production',true),/เพิกถอน/);assert.equal(posts,0);
    await db().query("UPDATE memberships SET active=true WHERE identity='sender'");
    await db().query('DELETE FROM flow_request_log');
    const unknown=await r.submit(sender,d.id,d.version,'production',true);assert.equal(unknown.status,'unknown');assert.equal(posts,1);
    assert.equal((await db().query("SELECT count(*)::int AS n FROM submission_attempts WHERE document_id=$1",[d.id])).rows[0].n,1);
    assert.equal((await db().query("SELECT status FROM draft_reviews WHERE document_id=$1 AND approved_version=$2",[d.id,d.version])).rows[0].status,'consumed');
    await assert.rejects(r.submit(sender,d.id,unknown.version,'production'));assert.equal(posts,1);
    const copy=await db().query("INSERT INTO receiving_documents(id,company_id,mode,body,totals,subtotal,vat,total,created_by,updated_by) SELECT gen_random_uuid(),company_id,mode,body,totals,subtotal,vat,total,created_by,updated_by FROM receiving_documents WHERE id=$1 RETURNING id",[d.id]);
    let changed=await r.read(approver,copy.rows[0].id);
    changed=await reviewAction(approver,changed.id,changed.version,'request-review','catalog test');
